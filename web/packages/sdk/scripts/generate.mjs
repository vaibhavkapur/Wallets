// Generates TypeScript types from the engine's JSON Schema and the
// application's OpenAPI document. Run after changing either contract.
import { compile } from "json-schema-to-typescript";
import openapiTS, { astToString } from "openapi-typescript";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import path from "node:path";

const here = path.dirname(fileURLToPath(import.meta.url));
const contracts = path.resolve(here, "../../../../contracts");
const out = path.resolve(here, "../src/generated");

const banner = "/* Generated by scripts/generate.mjs. Do not edit. */\n";

const schema = JSON.parse(await readFile(path.join(contracts, "engine-v1.schema.json"), "utf8"));
const engineTypes = await compile(schema, "EngineContractV1", {
  bannerComment: banner + "/* Source: contracts/engine-v1.schema.json (engine contract v1). */",
  additionalProperties: false,
  strictIndexSignatures: true,
});
await writeFile(path.join(out, "engine-contract.ts"), engineTypes);

const openapi = await readFile(path.join(contracts, "openapi.yaml"), "utf8");
const ast = await openapiTS(openapi, { exportType: true });
await writeFile(path.join(out, "api.ts"), banner + "/* Source: contracts/openapi.yaml. */\n" + astToString(ast));
console.log("generated", out);
